-- 2. 関数
-- ------------------------------------------------------------
-- 団体の種類×職 → 選挙の種類（選挙の種類は election の CHECK と同じ語）。admin_ward（行政区）は首長も議会も選挙がないので NULL
CREATE OR REPLACE FUNCTION policy_jp.news_lead_election_type(p_kind TEXT, p_office_kind TEXT) RETURNS TEXT
LANGUAGE sql IMMUTABLE SET search_path = pg_catalog, pg_temp AS $$
  SELECT CASE
           WHEN p_kind = 'admin_ward' THEN NULL
           WHEN p_office_kind = 'head' THEN CASE p_kind
             WHEN 'prefecture' THEN 'governor'
             WHEN 'special_ward' THEN 'ward_mayor'
             WHEN 'town' THEN 'town_mayor' WHEN 'village' THEN 'town_mayor'
             ELSE 'mayor' END
           WHEN p_office_kind = 'assembly' THEN CASE p_kind WHEN 'prefecture' THEN 'pref_assembly' ELSE 'muni_assembly' END
         END
$$;
COMMENT ON FUNCTION policy_jp.news_lead_election_type IS '団体の種類×職（head／assembly）→ 選挙の種類。指定都市・中核市・市＝mayor、特別区＝ward_mayor、町村＝town_mayor、都道府県＝governor、議会は pref_assembly／muni_assembly。行政区は NULL（選挙がない）';

-- 線索を作る／併合する（jp-news-fetch が呼ぶ）。戻り：{action: created|merged|capped|skipped, ...}
--   * 団体が無い・行政区・失効している → skipped
--   * 同じ団体×職の open な線索が ttl 内なら併合（記事を前に足して最大 5 件、item_count は URL の種類数）
--   * 新規は 1 日（日本時間）の上限 daily_lead_cap まで；超えたら capped（記事は後で見直されない：篩いの結果だけ残る）
CREATE OR REPLACE FUNCTION policy_jp.news_lead_record(p_lg_code TEXT, p_office_kind TEXT, p_signal TEXT, p_evidence JSONB, p_seen_on DATE DEFAULT NULL)
RETURNS JSONB
LANGUAGE plpgsql SET search_path = policy_jp, pg_temp AS $$
DECLARE
  v_today DATE := policy_jp.activity_today();
  v_seen DATE;
  v_ttl INTEGER;
  v_set policy_jp.news_settings%ROWTYPE;
  v_lead policy_jp.news_election_leads%ROWTYPE;
  v_ev JSONB;
  v_new_today INTEGER;
BEGIN
  IF p_office_kind NOT IN ('head', 'assembly') OR p_signal NOT IN ('resignation', 'death', 'dissolution', 'recall') THEN
    RAISE EXCEPTION 'news_lead_record: 職か信号が不正（%／%）', p_office_kind, p_signal;
  END IF;
  IF jsonb_typeof(p_evidence) <> 'array' OR jsonb_array_length(p_evidence) = 0 THEN RAISE EXCEPTION 'news_lead_record: evidence は 1 件以上の配列'; END IF;
  SELECT * INTO v_set FROM policy_jp.news_settings WHERE id = 1;
  IF NOT FOUND OR NOT v_set.enabled THEN RETURN jsonb_build_object('action', 'skipped', 'reason', 'disabled'); END IF;
  IF NOT EXISTS (SELECT 1 FROM policy_jp.local_governments g WHERE g.lg_code = p_lg_code AND g.valid_to IS NULL AND g.kind <> 'admin_ward') THEN
    RETURN jsonb_build_object('action', 'skipped', 'reason', 'no_such_lg');
  END IF;
  v_ttl := COALESCE((SELECT (r.params->>'ttl_days')::INTEGER FROM policy_jp.activity_rules r WHERE r.activity = 'news_discovery' AND r.enabled AND r.priority IS NULL ORDER BY r.id LIMIT 1), 60);
  v_seen := LEAST(COALESCE(p_seen_on, v_today), v_today);
  -- 古い open を失効にしてから探す（団体×職の open は 1 件の一意索引）
  UPDATE policy_jp.news_election_leads SET status = 'expired' WHERE status = 'open' AND lg_code = p_lg_code AND office_kind = p_office_kind AND signal_date + v_ttl < v_today;
  SELECT * INTO v_lead FROM policy_jp.news_election_leads WHERE status = 'open' AND lg_code = p_lg_code AND office_kind = p_office_kind FOR UPDATE;
  IF FOUND THEN
    -- 新しい記事を前に足し、URL の重複を除いて 5 件に切る
    SELECT jsonb_agg(t.value ORDER BY t.ord) INTO v_ev
      FROM (SELECT d.value, d.ord
              FROM (SELECT DISTINCT ON (x.value->>'url') x.value, x.ord
                      FROM jsonb_array_elements(p_evidence || v_lead.evidence) WITH ORDINALITY AS x(value, ord)
                     ORDER BY x.value->>'url', x.ord) d
             ORDER BY d.ord LIMIT 5) t;
    UPDATE policy_jp.news_election_leads l
       SET evidence = v_ev,
           item_count = l.item_count + (SELECT count(DISTINCT x->>'url') FROM jsonb_array_elements(p_evidence) x
                                         WHERE NOT EXISTS (SELECT 1 FROM jsonb_array_elements(l.evidence) o WHERE o->>'url' = x->>'url')),
           signals = (SELECT array_agg(DISTINCT s ORDER BY s) FROM unnest(l.signals || p_signal) s),
           last_seen_on = GREATEST(l.last_seen_on, v_seen)
     WHERE l.id = v_lead.id;
    RETURN jsonb_build_object('action', 'merged', 'lead_id', v_lead.id);
  END IF;
  SELECT count(*) INTO v_new_today FROM policy_jp.news_election_leads WHERE (created_at AT TIME ZONE 'Asia/Tokyo')::DATE = (now() AT TIME ZONE 'Asia/Tokyo')::DATE;
  IF v_new_today >= v_set.daily_lead_cap THEN RETURN jsonb_build_object('action', 'capped'); END IF;
  INSERT INTO policy_jp.news_election_leads (lg_code, office_kind, signal, signals, signal_date, last_seen_on, item_count, evidence)
  VALUES (p_lg_code, p_office_kind, p_signal, ARRAY[p_signal], v_seen, v_seen, (SELECT count(DISTINCT x->>'url') FROM jsonb_array_elements(p_evidence) x),
          (SELECT jsonb_agg(t.value ORDER BY t.ord) FROM (SELECT value, ord FROM jsonb_array_elements(p_evidence) WITH ORDINALITY AS y(value, ord) ORDER BY ord LIMIT 5) t))
  RETURNING * INTO v_lead;
  RETURN jsonb_build_object('action', 'created', 'lead_id', v_lead.id);
END
$$;
COMMENT ON FUNCTION policy_jp.news_lead_record IS '新聞の線索を団体×職ごとに作る／併合する。ttl（activity_rules.news_discovery の params.ttl_days、既定 60 日）内の続報は併合、新規は 1 日 daily_lead_cap まで。service_role だけ';

CREATE OR REPLACE FUNCTION policy_jp.news_purge() RETURNS INTEGER
LANGUAGE plpgsql SET search_path = policy_jp, pg_temp AS $$
DECLARE n INTEGER;
BEGIN
  DELETE FROM policy_jp.news_items WHERE id IN (
    SELECT i.id FROM policy_jp.news_items i
     WHERE i.fetched_at < now() - make_interval(days => (SELECT s.keep_days FROM policy_jp.news_settings s WHERE s.id = 1))
     ORDER BY i.id LIMIT 5000);
  GET DIAGNOSTICS n = ROW_COUNT;
  RETURN n;
END
$$;
COMMENT ON FUNCTION policy_jp.news_purge IS 'keep_days（news_settings）より古い記事を消す（1 回 5,000 件まで）。線索の evidence には写してあるので影響しない。pg_cron が毎日呼ぶ';

-- 呼び出し憑證（jp-system-one と同じ形：Vault に密鑰がなければ作り、関数は SHA-256 摘要で照合する）
DO $$
BEGIN
  IF to_regclass('vault.decrypted_secrets') IS NULL THEN RETURN; END IF;
  EXECUTE $q$
    SELECT vault.create_secret(
      encode(extensions.gen_random_bytes(32), 'hex'),
      'jp_news_cron_secret',
      'jp-news-fetch の pg_cron 呼び出し憑證（migration 20261011250000 が自動で作る；関数側は policy_jp.jp_news_cron_secret_ok で照合し、この値を持たない）'
    )
    WHERE NOT EXISTS (SELECT 1 FROM vault.decrypted_secrets WHERE name = 'jp_news_cron_secret')
  $q$;
END
$$;
CREATE OR REPLACE FUNCTION policy_jp.jp_news_cron_secret_ok(p_secret TEXT)
RETURNS BOOLEAN
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF p_secret IS NULL OR length(p_secret) < 16 THEN RETURN false; END IF;
  RETURN EXISTS (
    SELECT 1
      FROM vault.decrypted_secrets s
     WHERE s.name = 'jp_news_cron_secret'
       AND extensions.digest(s.decrypted_secret, 'sha256') = extensions.digest(p_secret, 'sha256')
  );
END
$$;
REVOKE ALL ON FUNCTION policy_jp.jp_news_cron_secret_ok(TEXT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION policy_jp.jp_news_cron_secret_ok(TEXT) TO service_role;
COMMENT ON FUNCTION policy_jp.jp_news_cron_secret_ok(TEXT) IS 'jp-news-fetch が x-cron-secret を照合する：入力値と Vault の jp_news_cron_secret を摘要で比べる。service_role だけ；密鑰は migration が作り、資料庫の外に出ない（jp_system_one_cron_secret_ok と同じ形）';

REVOKE EXECUTE ON FUNCTION policy_jp.news_lead_record(TEXT, TEXT, TEXT, JSONB, DATE), policy_jp.news_purge() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION policy_jp.news_lead_record(TEXT, TEXT, TEXT, JSONB, DATE), policy_jp.news_purge() TO service_role;

