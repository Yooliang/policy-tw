CREATE OR REPLACE FUNCTION policy_jp.politicians_reject_placeholder_name() RETURNS trigger
LANGUAGE plpgsql SET search_path = policy_jp, pg_temp AS $$
BEGIN
  IF NEW.review_status <> 'rejected' AND policy_jp.politician_name_is_placeholder(NEW.name, NEW.kana) THEN
    RAISE EXCEPTION '名前「%」（%）はテスト用のデータに見えます。本番のデータには入れられません', NEW.name, COALESCE(NEW.kana, '読みなし') USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END
$$;
COMMENT ON FUNCTION policy_jp.politicians_reject_placeholder_name IS '人物の名前（と読み）がテスト用に見えたら INSERT／UPDATE を拒む触発器関数。判定は politician_name_is_placeholder（20261011240000）。正見 politicians_reject_placeholder_name の日本版';
DROP TRIGGER IF EXISTS trg_politicians_reject_placeholder_name ON policy_jp.politicians;
CREATE TRIGGER trg_politicians_reject_placeholder_name
  BEFORE INSERT OR UPDATE OF name, kana ON policy_jp.politicians
  FOR EACH ROW EXECUTE FUNCTION policy_jp.politicians_reject_placeholder_name();

