-- 6. 測試名の人物を入力で拒む（正見 politicians_reject_placeholder_name の日本版・同じ判定 politician_name_is_placeholder(名前, 読み)）
--    INSERT と name／kana の UPDATE だけ見る：すでにいる測試名の人物（臂 placeholder_politicians が検出して removal する）を、他の列の更新で巻き込まない。
--    取り除き済み（review_status=rejected）への更新は通す
