CREATE TABLE IF NOT EXISTS policy_jp.news_sources (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label           TEXT NOT NULL CHECK (btrim(label) <> ''),
  kind            TEXT NOT NULL CHECK (kind IN ('media', 'government')),
  feed_url        TEXT NOT NULL UNIQUE CHECK (feed_url ~ '^https://'),
  format          TEXT NOT NULL CHECK (format IN ('rss', 'atom')),
  -- 地方紙・自治体の新着なら都道府県名（線索の手がかり）。全国紙は NULL
  region          TEXT,
  enabled         BOOLEAN NOT NULL DEFAULT TRUE,
  last_fetched_at TIMESTAMPTZ,
  last_error      TEXT,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE policy_jp.news_sources IS '日本の公開 RSS／Atom（新聞線の来源）。jp-news-fetch が毎時 enabled のものを取る；同じ来源は 30 分以内に取っていたら飛ばす。追加・停止は migration（種子はこの支）。正見 news_sources の日本版（sitemap_news と path_filter は日本の来源では使わないので持たない）';

CREATE TABLE IF NOT EXISTS policy_jp.news_items (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id    BIGINT NOT NULL REFERENCES policy_jp.news_sources(id) ON DELETE CASCADE,
  url          TEXT NOT NULL UNIQUE,
  title        TEXT NOT NULL,
  summary      TEXT,
  published_at TIMESTAMPTZ,
  fetched_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- 篩い済み：screened_at が入っていれば済み。screen.result＝no_entity（団体名なし）／no_signal（団体名はあるが辞職などの語なし）／lead（線索にした）／capped（上限で見送り）
