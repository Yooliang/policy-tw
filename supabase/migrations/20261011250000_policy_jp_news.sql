-- 日本站「新聞線」（突発の選挙）＋測試名人物の入力拒否と派工の隔離（工作単 Yooliang/policy-ops#95）
-- ============================================================
--
-- 設計：policy-jp docs/PLAN-election-chain.md 第 4 節（頭の 3 つ目の缺口來源）、docs/JEV-comparison.md F 列。
-- 正見の做法（news-fetch → news_items → system-one?action=news_screen）を日本站に搬んだもの。差異：
--   * 正見の news_screen は「新聞に出てくる政治人物 × 既存政見の進度」を聞く。日本版は「団体名＋首長／議会＋辞職・死去・解散・リコール」を
--     **安い規則で篩う**だけ（人物も政見も聞かない）。出口は新任務型ではなく既存の election_discovery（target.discovery='news'）。
--   * Jev の判定（「この記事は選挙を要するか」）はこの支では入れない（次の刀）。そのため篩いは厳しく（団体名＋職名が隣り合う・勧告や要求は除外・
--     団体×職ごとに 1 件・1 日の新規上限 news_settings.daily_lead_cap）し、代理が選管の告示で確かめる（報道は手がかりで出典ではない）。
--   * 来源は Vault に新しい密鑰を作る（jp_news_cron_secret、migration が自動生成、手で設定する secret はない）＝ jp-system-one と同じ。
--
-- この支でやること（すべて policy_jp。public／ditrust には触れない）：
-- 1. 新聞の表：news_sources（来源、種子 5 件）／news_items（逐則）／news_settings（単列）／news_election_leads（団体×職の線索）。anon には開かない（見出しと要約の再配布をしない）。
-- 2. RPC：news_lead_record（線索の作成／併合、1 日の新規上限、ttl）、news_purge（古い記事を消す）、news_lead_election_type、jp_news_cron_secret_ok。
-- 3. 派工臂 news_discovery（task_type=election_discovery、task_id＝auto:election_discovery:<線索の日付>:<団体コード>:<head|assembly>、
--    target.discovery='news'）。総表 UNION 1 行・activity_arm_names 1 つ・規則 2 条（news_discovery 常時窓＋priority:news_discovery 前段）・console_arm_stage_map。
--    chain_step_rank は task_type が election_discovery のままなので動かさない（1 のまま）。
-- 4. pg_cron：policy-jp-news-fetch-hourly（毎時 23 分、jp-news-fetch）／policy-jp-news-purge-daily。
-- 5. 測試名人物：politician_name_is_placeholder で入力を拒む触発器（正見 politicians_reject_placeholder_name の日本版）と、
--    総表での隔離（正見 20261008114000 の日本版：target に測試名人物の id がある他臂の任務を出さない）。
--
-- 守門：_shared/policy-jp-news.test.ts、policy-jp-placeholder-guard.test.ts、jp/news-screen.test.ts、policy-jp-dispatch-drift.test.ts（JP_ONLY 登記）。冪等、尾端自我檢查。

