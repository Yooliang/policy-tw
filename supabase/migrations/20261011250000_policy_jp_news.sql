CREATE OR REPLACE FUNCTION policy_jp.contribution_auto_tasks_news_discovery()
RETURNS TABLE (task_id TEXT, task_type TEXT, target JSONB, what_we_need TEXT, hint_sources TEXT[], reward INTEGER, region TEXT)
LANGUAGE sql STABLE SET search_path = policy_jp, pg_temp AS $$
  WITH p AS (
    SELECT (r.params->>'cap')::INTEGER AS cap,
           COALESCE((r.params->>'ttl_days')::INTEGER, 60) AS ttl_days,
           COALESCE((r.params->>'min_items')::INTEGER, 1) AS min_items,
           policy_jp.activity_today() AS today
      FROM policy_jp.activity_rules r
     WHERE r.activity = 'news_discovery' AND r.enabled AND r.priority IS NULL
     ORDER BY r.id LIMIT 1
  ),
  gaps AS (
    SELECT l.*, g.name AS lg_name, g.kind AS lg_kind, pr.name AS pref_name, p.ttl_days,
           policy_jp.news_lead_election_type(g.kind, l.office_kind) AS election_type,
           'auto:election_discovery:' || l.signal_date || ':' || l.lg_code || ':' || l.office_kind AS tid
      FROM policy_jp.news_election_leads l
      JOIN policy_jp.local_governments g ON g.lg_code = l.lg_code
      JOIN policy_jp.local_governments pr ON pr.lg_code = g.pref_code
      CROSS JOIN p
     WHERE p.cap IS NOT NULL
       AND l.status = 'open' AND l.item_count >= p.min_items
       AND l.signal_date <= p.today AND l.signal_date + p.ttl_days >= p.today
       AND g.valid_to IS NULL AND g.kind <> 'admin_ward'
       -- すでにその団体×職の選挙が記録されている（線索の日付の少し前から、ttl＋60 日先まで）なら缺口ではない
       AND NOT EXISTS (
         SELECT 1 FROM policy_jp.elections e
          WHERE e.lg_code = l.lg_code AND e.review_status <> 'rejected'
            AND e.election_type IN ('governor', 'mayor', 'ward_mayor', 'town_mayor', 'pref_assembly', 'muni_assembly')
            AND (l.office_kind = 'head') = (e.election_type IN ('governor', 'mayor', 'ward_mayor', 'town_mayor'))
            AND e.election_date BETWEEN l.signal_date - 7 AND l.signal_date + p.ttl_days + 60)
       -- cap は「可派」の前 N 件（#503 と同じ）：查無（冷卻中）・飽和・通過等落庫のものを先に外す
       AND NOT policy_jp.task_unavailable('auto:election_discovery:' || l.signal_date || ':' || l.lg_code || ':' || l.office_kind)
     ORDER BY l.signal_date DESC, l.lg_code, l.office_kind
     LIMIT (SELECT cap FROM p)
  )
  SELECT g.tid, 'election_discovery',
         jsonb_build_object('discovery', 'news', 'lg_code', g.lg_code, 'pref_name', g.pref_name, 'lg_name', g.lg_name,
                            'office_kind', g.office_kind, 'election_type', g.election_type,
                            'signal', g.signal, 'signals', to_jsonb(g.signals), 'signal_date', g.signal_date, 'item_count', g.item_count,
                            'statutory_days', CASE g.signal WHEN 'dissolution' THEN 40 WHEN 'recall' THEN NULL ELSE 50 END,
                            'lead_until', g.signal_date + g.ttl_days, 'news', g.evidence),
         g.lg_name || 'の' || CASE WHEN g.office_kind = 'head' THEN '長' ELSE '議会議員' END || 'について、'
           || CASE g.signal WHEN 'resignation' THEN '辞職（失職を含む）' WHEN 'death' THEN '死去' WHEN 'dissolution' THEN '議会の解散' ELSE 'リコール（解職・解散の請求や住民投票）' END
           || 'を報じる記事が見つかりました：「' || COALESCE(g.evidence->0->>'title', '') || '」（' || COALESCE(g.evidence->0->>'source', '') || '）' || COALESCE(g.evidence->0->>'url', '') || '。'
           || '報道は手がかりであって出典ではありません。'
