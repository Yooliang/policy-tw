DO $$
BEGIN
  IF NOT ('news_discovery' = ANY (policy_jp.activity_arm_names())) THEN RAISE EXCEPTION 'policy_jp：activity_arm_names() に news_discovery がない'; END IF;
  IF NOT EXISTS (SELECT 1 FROM policy_jp.activity_rules r WHERE r.activity = 'news_discovery' AND r.priority IS NULL AND r.enabled AND r.window_kind = 'always' AND r.after_step IS NULL AND r.params ? 'cap' AND r.params ? 'ttl_days') THEN
    RAISE EXCEPTION 'policy_jp：news_discovery の規則が「開いている・常時・after_step なし・cap と ttl_days あり」になっていない';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM policy_jp.activity_rules r WHERE r.activity = 'priority:news_discovery' AND r.priority = 1) THEN RAISE EXCEPTION 'policy_jp：priority:news_discovery がない'; END IF;
  IF (SELECT count(*) FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
       WHERE n.nspname = 'policy_jp' AND p.proname = 'contribution_auto_tasks_arms'
         AND pg_get_functiondef(p.oid) LIKE '%contribution_auto_tasks_news_discovery()%'
         AND pg_get_functiondef(p.oid) LIKE '%ph AS MATERIALIZED%') <> 1 THEN
    RAISE EXCEPTION 'policy_jp：総表に news_discovery の分支と測試名人物の隔離がない';
  END IF;
  IF has_function_privilege('anon', 'policy_jp.contribution_auto_tasks_news_discovery()', 'EXECUTE')
     OR has_function_privilege('anon', 'policy_jp.news_lead_record(text,text,text,jsonb,date)', 'EXECUTE')
     OR has_function_privilege('anon', 'policy_jp.news_purge()', 'EXECUTE')
     OR has_function_privilege('anon', 'policy_jp.jp_news_cron_secret_ok(text)', 'EXECUTE') THEN
    RAISE EXCEPTION 'policy_jp：新聞線の内部関数を anon に渡してはいけない';
  END IF;
  IF has_table_privilege('anon', 'policy_jp.news_items', 'SELECT') OR has_table_privilege('anon', 'policy_jp.news_election_leads', 'SELECT') THEN
    RAISE EXCEPTION 'policy_jp：新聞の表を anon に開いてはいけない';
  END IF;
  IF policy_jp.chain_step_rank('auto:election_discovery:2026-10-13:232033:head', 'election_discovery') <> 1 THEN RAISE EXCEPTION 'policy_jp：election_discovery の順位が動いた'; END IF;
  IF policy_jp.news_lead_election_type('prefecture', 'head') <> 'governor' OR policy_jp.news_lead_election_type('town', 'head') <> 'town_mayor'
     OR policy_jp.news_lead_election_type('designated_city', 'assembly') <> 'muni_assembly' OR policy_jp.news_lead_election_type('admin_ward', 'head') IS NOT NULL THEN
    RAISE EXCEPTION 'policy_jp：news_lead_election_type の対応がおかしい';
  END IF;
END
$$;

