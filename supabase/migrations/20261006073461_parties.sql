CREATE TABLE IF NOT EXISTS parties (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           TEXT NOT NULL CHECK (btrim(name) <> ''),
  short_name     TEXT,
  valid_from     DATE,
  valid_to       DATE,
  predecessor_id BIGINT REFERENCES parties(id),
  moi_no         INTEGER UNIQUE,
  moi_name       TEXT,
  moi_status     TEXT CHECK (moi_status IN ('一般', '撤銷備案', '自行解散', '失聯', '廢止備案')),
  note           TEXT,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT parties_valid_period CHECK (valid_from IS NULL OR valid_to IS NULL OR valid_to >= valid_from),
  CONSTRAINT parties_moi_fields CHECK ((moi_no IS NULL) = (moi_status IS NULL) AND (moi_no IS NULL) = (moi_name IS NULL))
);
COMMENT ON TABLE parties IS
  '政黨（#346 第一階段）：內政部政黨名冊一個政黨一列（id＝政黨編號），加上資料裡出現、名冊查無此名稱的（id 10001 起）。'
  '改名視為新的一筆（predecessor_id 指舊名）。無黨籍不是政黨、不建列';
COMMENT ON COLUMN parties.name IS '正式名稱（照名冊；名冊加的註記不算名稱，原文在 moi_name）';
COMMENT ON COLUMN parties.short_name IS '簡稱（畫面用；只有資料真的用到的通稱才填）';
COMMENT ON COLUMN parties.valid_from IS '這個名稱開始有效的日期：名冊的成立日期；改過名的現名在查到改名日之前空著';
COMMENT ON COLUMN parties.valid_to IS '這個名稱停止有效的日期。名冊的解散、廢止沒有日期，所以目前一律空著——空的不代表還在，看 moi_status';
COMMENT ON COLUMN parties.predecessor_id IS '改名前的那一筆';
COMMENT ON COLUMN parties.moi_no IS '內政部政黨編號；名冊查無此名稱的是空的';
COMMENT ON COLUMN parties.moi_status IS '名冊上的政黨狀態：一般／撤銷備案／自行解散／失聯／廢止備案（擷取日當時）';
CREATE INDEX IF NOT EXISTS idx_parties_name ON parties (name);

CREATE TABLE IF NOT EXISTS party_aliases (
  alias_key TEXT PRIMARY KEY,
  alias     TEXT NOT NULL,
  party_id  BIGINT REFERENCES parties(id) ON DELETE CASCADE,
  kind      TEXT NOT NULL CHECK (kind IN ('name', 'short', 'variant', 'independent')),
  note      TEXT,
  CONSTRAINT party_aliases_independent CHECK ((kind = 'independent') = (party_id IS NULL))
);
COMMENT ON TABLE party_aliases IS
  '資料裡的政黨寫法 → parties（#346）。alias_key＝party_alias_key(寫法)。kind：name 正式名稱／short 簡稱／variant 異寫／independent 無黨籍那一族（party_id 空的）';
CREATE INDEX IF NOT EXISTS idx_party_aliases_party ON party_aliases (party_id);

