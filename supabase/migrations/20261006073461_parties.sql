-- 2. 比對規則（前端 lib/parties.ts 的 partyAliasKey、腳本 scripts/fetch-moi-parties.py 的 alias_key 同一套，測試盯）
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION party_alias_key(p_text TEXT) RETURNS TEXT
LANGUAGE sql IMMUTABLE AS $$
  SELECT nullif(replace(regexp_replace(normalize(coalesce(p_text, ''), NFKC), '\s', '', 'g'), '臺', '台'), '')
$$;
COMMENT ON FUNCTION party_alias_key IS '政黨寫法比對用的字：全形轉半形（NFKC）→ 去掉所有空白 → 「臺」當「台」；空的回 NULL（#346）';

CREATE OR REPLACE FUNCTION party_id_of(p_text TEXT) RETURNS BIGINT
LANGUAGE sql STABLE AS $$
  SELECT a.party_id FROM party_aliases a WHERE a.alias_key = party_alias_key(p_text)
$$;
COMMENT ON FUNCTION party_id_of IS '政黨文字 → parties.id；無黨籍那一族與不在對照表的都回 NULL（要分清楚看 party_aliases 有沒有那一列）';

