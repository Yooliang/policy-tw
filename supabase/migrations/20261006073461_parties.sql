-- 政黨表 parties＋寫法對照 party_aliases；人物與參選紀錄加 party_id（#346 第一階段，只加不刪）
--
-- 為什麼：政黨在正見只是 politicians.party 一欄自由文字。同一個政黨有好幾種寫法（「中國國民黨」「國民黨」、
-- 「台灣基進」「台灣基進黨」），無黨籍有四種寫法，政黨改名、解散也沒有地方記。日本站（keifu SCHEMA v0.7）
-- 是 parties 一表、有效期間、改名視為新的一筆，參選紀錄記「本人當時所屬的政黨」，無黨籍是 party_id 空著。
--
-- 這支做的事（都是加，舊的 politicians.party 文字欄位保留、寫入端照舊寫文字）：
--   1. parties：內政部政黨名冊（政黨資訊網「查政黨」全部狀態匯出，2026-10-06 擷取 397 個，含已解散、廢止的）一個政黨一列，
--      加上資料裡出現、名冊查無此名稱的 6 列。名冊上的政黨 id＝政黨編號（網址 /party/:id 用、穩定），名冊外的從 10001 起。
--      名稱照名冊；名冊加的註記（「中華統一促進黨（115年8月7日內政部向憲法法庭聲請違憲解散）」）不是名稱，原文存 moi_name。
--      有效期間（valid_from／valid_to）＝這個名稱的有效期間，改名視為新的一筆：
--        - valid_from 填名冊的「成立日期」。名冊只登記現名、沒有改名紀錄，所以知道改過名的（台灣團結聯盟 → 台聯黨），
--          舊名那一列放成立日期、現名那一列 valid_from 空著、predecessor_id 指到舊名，界線日期待查。
--        - valid_to 一律空著：名冊的解散、廢止只有狀態沒有日期，看 moi_status；**valid_to 空的不代表還在**。
--      出處：名冊頁（sources 一列，source_refs target_table＝parties）。資料段由 scripts/fetch-moi-parties.py 產生，
--      同一份也寫在 lib/party-seed.json（前端建置在這支還沒套上的那一次用它，測試盯兩邊一致）。
--   2. party_aliases：資料裡的寫法 → 政黨。比「正規化後的字」（party_alias_key：全形轉半形、去空白、臺當台）。
--      名冊上每個名稱一條（同名重新備案的只對到狀態一般的那一個），外加資料裡真的出現過的別寫法，每條都有理由：
--        國民黨→中國國民黨、民進黨→民主進步黨、民眾黨→台灣民眾黨、綠黨→台灣綠黨（簡稱）；台灣基進黨→台灣基進（名冊沒有「黨」字）。
--      **無黨籍不是政黨**（日本站 v0.3 同一個決定）：「無黨籍」「無黨籍及未經政黨推薦」（中選會名冊的寫法）
--      「無黨籍及未經政黨推薦者」「未經政黨推薦」「無」「無黨」六種寫法對照到「無黨籍」（kind＝independent、party_id 空的）。
--      2026-10-06 資料裡出現的 77 種寫法（人物表＋已落庫的 candidacy／politician 交件）全部有對照。
--   3. politicians.party_id：照人物的政黨文字對照（觸發器：文字一改就重對）。對不到的寫法 party_id 空著，
--      列在視圖 party_alias_gaps——**人物的 party_id 空的有兩種意思**：文字是無黨籍那一族＝無黨籍；不在對照表＝還沒對照。
--   4. politician_elections.party_id＋party_basis（本人在那一次參選時所屬的政黨；日本站同欄位）：
--        - contribution：candidacy 交件寫的 party（同儕驗證過的那一次參選的資料）。已落庫的照落庫順序回填，
--          之後每筆 candidacy 落庫由觸發器寫（一人一屆只有一筆參選紀錄，主鍵 politician_id＋election_id，寫的就是那一筆）。
--        - person_single：這個人只有這一筆參選紀錄，而且人物的政黨從沒被改過（edit_history 沒有 party 的變動）——
--          人物的政黨文字就是建這筆紀錄時一起寫進來的（2022 中選會名冊整批匯入的那一萬多位都是這種），只在回填時用。
--        - 空的：看不出那一次是什麼黨（同一人有好幾屆、又沒有交件寫政黨）；**不拿人物現在的政黨去填過去的參選**。
--      party_basis 有值而 party_id 空的＝那一次是無黨籍；party_basis 空的＝不知道。
--
-- 沒做的（第二階段）：畫面改讀 party_id（第一階段政黨頁照人物的政黨文字對照、跟選舉頁卡片同一個依據）；
-- 交件改交 party_id；cec-sync 把中選會名冊的推薦政黨一起存，補齊已投票屆別參選紀錄的政黨；確認後才刪文字欄位。

