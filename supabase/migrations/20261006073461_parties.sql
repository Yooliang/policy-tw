-- candidacy 交件 → 那一筆參選紀錄的政黨。回傳改了幾筆（0 或 1）
CREATE OR REPLACE FUNCTION politician_election_party_from_candidacy(p_politician_id UUID, p_payload JSONB) RETURNS INTEGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_alias party_aliases%ROWTYPE;
  v_eid INTEGER;
  v_pe INTEGER;
  v_n INTEGER;
BEGIN
  IF p_politician_id IS NULL OR party_alias_key(p_payload ->> 'party') IS NULL THEN RETURN 0; END IF;
  SELECT * INTO v_alias FROM party_aliases WHERE alias_key = party_alias_key(p_payload ->> 'party');
  IF NOT FOUND THEN RETURN 0; END IF;  -- 寫法還沒有對照：不猜（列在 party_alias_gaps）
  IF coalesce(p_payload ->> 'election_id', '') !~ '^[0-9]+$' THEN RETURN 0; END IF;
  v_eid := (p_payload ->> 'election_id')::INTEGER;
  -- 一人一屆只有一筆參選紀錄（主鍵 politician_id＋election_id），candidacy 落庫寫的就是這一筆
  SELECT pe.id INTO v_pe FROM politician_elections pe WHERE pe.politician_id = p_politician_id AND pe.election_id = v_eid;
  IF v_pe IS NULL THEN RETURN 0; END IF;
  UPDATE politician_elections
     SET party_id = v_alias.party_id, party_basis = 'contribution'
   WHERE id = v_pe AND (party_id IS DISTINCT FROM v_alias.party_id OR party_basis IS DISTINCT FROM 'contribution');
  GET DIAGNOSTICS v_n = ROW_COUNT;
  RETURN v_n;
END;
$$;
REVOKE EXECUTE ON FUNCTION politician_election_party_from_candidacy(UUID, JSONB) FROM PUBLIC, anon, authenticated;
COMMENT ON FUNCTION politician_election_party_from_candidacy IS
  'candidacy 交件寫的 party → 那一筆參選紀錄的 party_id（party_basis＝contribution）；回填與落庫觸發器共用（#346）';

-- 回填一：已落庫的 candidacy 交件，照落庫順序（後面的蓋前面的，跟之後的觸發器一樣）
DO $$
DECLARE
  r RECORD;
  v_n INTEGER := 0;
BEGIN
  FOR r IN
    SELECT c.applied_politician_id, c.payload
      FROM contributions c
     WHERE c.contribution_type = 'candidacy' AND c.status = 'applied' AND c.applied_politician_id IS NOT NULL
     ORDER BY coalesce(c.applied_at, c.created_at), c.id
  LOOP
    v_n := v_n + politician_election_party_from_candidacy(r.applied_politician_id, r.payload);
  END LOOP;
  RAISE NOTICE '參選紀錄政黨（交件）：寫了 % 次，最後 % 筆',
    v_n, (SELECT count(*) FROM politician_elections WHERE party_basis = 'contribution');
END $$;

-- 回填二：只有這一筆參選紀錄、人物政黨沒改過、文字有對照的人——人物的政黨就是這一次參選時的政黨
UPDATE politician_elections pe
   SET party_id = a.party_id, party_basis = 'person_single'
  FROM politicians p
  JOIN party_aliases a ON a.alias_key = party_alias_key(p.party)
 WHERE p.id = pe.politician_id
   AND pe.party_basis IS NULL
   AND (SELECT count(*) FROM politician_elections q WHERE q.politician_id = pe.politician_id) = 1
   AND NOT EXISTS (SELECT 1 FROM edit_history h
                    WHERE h.table_name = 'politicians' AND h.record_id = p.id::TEXT AND h.field = 'party' AND h.reverted_at IS NULL);

-- 之後：candidacy 落庫就寫
CREATE OR REPLACE FUNCTION contribution_applied_candidacy_party() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NEW.contribution_type = 'candidacy' AND NEW.applied_politician_id IS NOT NULL THEN
    BEGIN
      PERFORM politician_election_party_from_candidacy(NEW.applied_politician_id, NEW.payload);
    EXCEPTION WHEN OTHERS THEN
      -- 不擋落庫；漏掉的會留在 party_basis 空的那一堆
      RAISE WARNING 'politician_election_party_from_candidacy（交件 %）失敗：%', NEW.id, SQLERRM;
    END;
  END IF;
  RETURN NULL;
END;
$$;
DROP TRIGGER IF EXISTS trg_contribution_applied_candidacy_party ON contributions;
CREATE TRIGGER trg_contribution_applied_candidacy_party
  AFTER UPDATE OF status ON contributions
  FOR EACH ROW WHEN (NEW.status = 'applied' AND OLD.status IS DISTINCT FROM 'applied')
  EXECUTE FUNCTION contribution_applied_candidacy_party();

-- ------------------------------------------------------------
-- 6. 檢查：資料裡有、對照表沒有的寫法（正常是空的；有就補一條對照，不要猜）
-- ------------------------------------------------------------
CREATE OR REPLACE VIEW party_alias_gaps AS
SELECT t.party_text, sum(t.n)::INTEGER AS n, array_agg(DISTINCT t.where_from) AS where_from
  FROM (
    SELECT p.party AS party_text, count(*) AS n, 'politicians' AS where_from
      FROM politicians p WHERE p.merged_into IS NULL GROUP BY p.party
    UNION ALL
    SELECT c.payload ->> 'party', count(*), 'candidacy'
      FROM contributions c
     WHERE c.contribution_type = 'candidacy' AND c.status = 'applied' AND party_alias_key(c.payload ->> 'party') IS NOT NULL
     GROUP BY 1
  ) t
 WHERE NOT EXISTS (SELECT 1 FROM party_aliases a WHERE a.alias_key = party_alias_key(t.party_text))
 GROUP BY t.party_text;
COMMENT ON VIEW party_alias_gaps IS '人物表或已落庫的 candidacy 交件裡出現、party_aliases 對不到的政黨寫法（正常是空的，#346）';
ALTER VIEW party_alias_gaps SET (security_invoker = on);
GRANT SELECT ON party_alias_gaps TO anon, authenticated;

