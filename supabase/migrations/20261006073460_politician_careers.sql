         1, p.region
    FROM per x
    JOIN politicians p ON p.id = x.politician_id AND p.merged_into IS NULL
   WHERE NOT EXISTS (SELECT 1 FROM inflight i WHERE i.pid = p.id::TEXT)
$$;
