-- 學經歷獨立成表 politician_careers，每一項各自帶出處（#346 第一階段，只加不刪）
--
-- 為什麼：人物頁的「學歷」「經歷」讀 politicians.education[]／experience[] 兩個陣列，陣列掛不上出處——
-- 一項學歷是誰查的、看的是哪一頁，資料庫答不出來。日本站（keifu SCHEMA v0.7）從一開始就是
-- politician_careers 一項一列、每項都要出處；正見照它的形狀，出處走 #347 的 sources／source_refs。
--
-- 這支做的事（都是加，沒有刪、沒有改名）：
--   1. 新表 politician_careers：一個人的一項學歷或經歷一列（kind＝education／career，照日本站），
--      文字照陣列原樣、起訖年（start_year／end_year）先空著——陣列只有文字，起訖要等第二階段交件能帶。
--   2. 回填：兩個陣列逐項搬進來（搬移，不是新資料）。2026-10-06 唯讀：學歷 59 人 153 項、經歷 56 人 348 項。
--   3. 出處回填：學經歷是「politician 型別交件、驗證通過、落庫」進來的，那筆交件的 source_urls 就是它的出處；
--      照落庫順序把每筆已落庫交件的網址掛到「文字相同」的項目上（source_refs，target_table＝politician_careers）。
--      其餘（早期整批匯入、舊 AI 管線寫的）沒有出處——不編，標「待補出處」（視圖 politician_careers_full 的 needs_source）。
--      **臉書、IG、Threads 讀不到，不算出處**（#349 同一份清單，supabase/functions/_shared/lineage.ts 的 UNREADABLE_SOCIAL_HOSTS）。
--   4. 同步：陣列欄位保留，任何寫入端照舊寫陣列；陣列一變，觸發器把這個人的學經歷重新對一次
--      （新項目加列、拿掉的項目刪列連同它的出處引用、順序照陣列）。交件落庫（contributions.status 變成 applied）
--      時，politician 型別帶 education／experience 的，觸發器照第 3 點同一條規則把 source_urls 掛上去——
--      **陣列沒變也會掛**：補出處任務的代理是照原文重交同一份學經歷，落庫只補空欄位（fillBlanks），陣列不會動。
--   5. 派工：沒有出處的學經歷，一個人一件「補學經歷條列」任務（沿用 profile_detail_gap 型別，
--      target.kind＝career_sources、task_id＝auto:profile_detail_gap:sources:<人物>），代理找到看得到那幾項的頁面，
--      用 politician 型別照原文重交那幾項＋source_urls；已經有人交了還在等票的先不派。
--   6. 檢查：視圖 politician_careers_drift 列出「陣列有、表沒有」或「表有、陣列沒有」的項目，正常是空的
--      （觸發器出錯只記警告、不擋寫入，跟 #347 出處同步同一個做法，所以要有地方看得到漏了什麼）。
--
-- 沒做的（第二階段）：人物頁改讀這張表、每項附出處或標「待補出處」；交件直接寫這張表（可帶起訖年）、
-- 陣列改成由表衍生，確認兩邊一致後才刪陣列欄位。

-- ------------------------------------------------------------
-- 1. 表
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS politician_careers (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  politician_id UUID NOT NULL REFERENCES politicians(id) ON DELETE CASCADE,
  kind          TEXT NOT NULL CHECK (kind IN ('education', 'career')),
  text          TEXT NOT NULL CHECK (btrim(text) <> ''),
  text_key      TEXT NOT NULL,
  start_year    INTEGER CHECK (start_year BETWEEN 1900 AND 2100),
  end_year      INTEGER CHECK (end_year BETWEEN 1900 AND 2100),
  sort_order    INTEGER NOT NULL DEFAULT 0,
  origin        TEXT NOT NULL,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT politician_careers_years CHECK (start_year IS NULL OR end_year IS NULL OR end_year >= start_year),
  CONSTRAINT politician_careers_unique UNIQUE (politician_id, kind, text_key)
);
COMMENT ON TABLE politician_careers IS
  '學經歷，一項一列（#346 第一階段）。kind：education 學歷／career 經歷（照日本站）。出處走 sources／source_refs（target_table＝politician_careers）；'
  '沒有出處＝待補出處（看 politician_careers_full.needs_source）。第一階段由 politicians.education[]／experience[] 經觸發器同步，不要直接寫';
COMMENT ON COLUMN politician_careers.text IS '照陣列原文（去頭尾空白）';
COMMENT ON COLUMN politician_careers.text_key IS '比對用的正規化文字（career_text_key：全形轉半形、連續空白收成一個）；同一人同一種只有一列';
COMMENT ON COLUMN politician_careers.start_year IS '起始年（西元）；第一階段陣列沒有這個資訊，一律空著';
COMMENT ON COLUMN politician_careers.end_year IS '結束年（西元）；第一階段一律空著';
COMMENT ON COLUMN politician_careers.sort_order IS '在陣列裡的順序（從 1 起）';
COMMENT ON COLUMN politician_careers.origin IS '這一列怎麼來的：backfill:array（10-06 回填）／array_sync（之後陣列變動同步）';
CREATE INDEX IF NOT EXISTS idx_politician_careers_politician ON politician_careers (politician_id, kind, sort_order);

ALTER TABLE politician_careers ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Public read" ON politician_careers;
CREATE POLICY "Public read" ON politician_careers FOR SELECT USING (true);
DROP POLICY IF EXISTS "Service role write" ON politician_careers;
