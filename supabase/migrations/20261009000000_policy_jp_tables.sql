-- 日本站（政策の系譜）第一批資料表：policy_jp schema（policy-jp #39 ①）
-- ============================================================
--
-- 這支只在 policy_jp 裡建表，不碰 public、ditrust，不碰正見既有的函式、cron、Edge Function。
-- 前提：20261008195000_policy_jp_schema.sql（#479）已建好空的 policy_jp 與基本權限
--       （USAGE 給 anon／authenticated／service_role；service_role 對之後的物件有完整權限；函式預設不給 PUBLIC 執行）。
--
-- 形狀：照日本站 docs/SCHEMA.md v0.7，並一次對齊正見現在的寫法（issue #39 ① 的 11 點）：
--   1. 出處改用 source_refs（source_id、target_table、target_id、role、origin），各表不再放 source_ids 陣列（同正見 #354／#404／#416）。
--      參選狀態的出處（SCHEMA 的 status_source_ids）用 target_table='politician_election_status' 跟參選本身的出處分開。
--      查核紀錄的依據（SCHEMA 的 evidence_source_ids）用 target_table='reviews'。
--   2. sources：url UNIQUE、加 origin、fetched_at 可空；source_kind 保留日本的六個值（見欄位註解）。
--   3. self_evidence 只收 linked_by_official、mutual_link（拿掉 platform_verified，同正見協議 1.62.0：社群貼文不能標 self）。
--   4. politician_offices 加 end_reason、end_basis（有卸任日兩欄都必填）、politician_election_id。
--   5. politician_elections 加 withdrawn_after_filing、party_basis；狀態欄位叫 candidacy_status（六個值）。
--   6. election_districts 加 seats_basis（law／notice）；is_uncontested 放在選舉區這一層（elections 不放）。
--   7. elections：election_reason 加 rerun；加 level、jurisdiction、timezone；name、lineage_id 進表；candidates_count 不存（要時算）；
--      字串 id＝正見的 election_key（建立後不改）。
--   8. politician_careers：加 id；sort_order（SCHEMA 樣品的 seq 改名）；(politician_id, kind, text) 不重複。
--   9. parties：加 short_name、predecessor_id、note。
--  10. lineages 加 level、lg_code 可空；新表 lineage_participants、lineage_links（同正見 #378）；handovers 加 source_locator。
--  11. 不建得票數、得票率的欄位，也不建票數備份表（日本站規矩）。檔尾的檢查擋住任何 vote／得票 字樣的欄位。
--
-- 權限：
--   * 每張表都 ENABLE ROW LEVEL SECURITY。
--   * anon、authenticated：逐表 GRANT SELECT，沒有任何 INSERT／UPDATE／DELETE 權限，也沒有寫入用的 policy。
--     有 review_status 的表，公開讀只看得到 published（SCHEMA：畫面只顯示 published）；參照用的表（団体、政黨、會派、出處…）全部可讀。
--   * 寫入一律由 service_role（Edge Function／之後的寫入函式）做；service_role 在 Supabase 有 BYPASSRLS，
--     表的權限來自 #479 的 ALTER DEFAULT PRIVILEGES。這一批沒有寫入函式（② 派工機制、③ 的任務落庫時才加）。
--   * 選舉列一律經任務回報建立（③：找缺口→派 election_discovery→代理附官方出處回報→共識才寫入），程式不推算、不自動建列；
--     所以 elections 沒有「推定／確定」之類給系統推算用的欄位。
--   * 檔尾的檢查：policy_jp 裡沒開 RLS 的表、anon／authenticated 有寫入權限的表，都會讓這支 migration 失敗。
--
-- id：日本站的資料目前是 JSON 樣品，id 都是字串（elections 的 id 規則見表註解），這裡照用 TEXT；
--     只有 sources 照正見用 BIGINT（source_refs.source_id 要跟正見同型別）。
-- 守門：supabase/functions/_shared/policy-jp-tables.test.ts（PGlite 實跑這支 migration：權限、RLS、CHECK、沒有票數欄位）。

