DO $$
DECLARE bad TEXT;
BEGIN
  -- (a) 每張表都開 RLS
  SELECT string_agg(c.relname, ', ') INTO bad
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'policy_jp' AND c.relkind = 'r' AND NOT c.relrowsecurity;
  IF bad IS NOT NULL THEN RAISE EXCEPTION 'policy_jp：這些表沒開 RLS：%', bad; END IF;

  -- (b) anon／authenticated 沒有任何寫入權限
  SELECT string_agg(DISTINCT g.table_name || ':' || g.grantee || ':' || g.privilege_type, ', ') INTO bad
    FROM information_schema.role_table_grants g
   WHERE g.table_schema = 'policy_jp' AND g.grantee IN ('anon', 'authenticated', 'PUBLIC')
     AND g.privilege_type IN ('INSERT', 'UPDATE', 'DELETE', 'TRUNCATE', 'REFERENCES', 'TRIGGER');
  IF bad IS NOT NULL THEN RAISE EXCEPTION 'policy_jp：anon／authenticated 不該有寫入權限：%', bad; END IF;

