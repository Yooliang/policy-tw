CREATE OR REPLACE FUNCTION policy_jp.touch_updated_at() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path = policy_jp, pg_temp AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

-- 全国地方公共団体コード（6 碼）的檢查碼：前 5 碼乘 6,5,4,3,2，總和除以 11 的餘數 r，檢查碼＝(11−r) mod 10（總務省代碼表 1,965 筆全部吻合）
CREATE OR REPLACE FUNCTION policy_jp.lg_code_valid(p_code TEXT) RETURNS BOOLEAN
LANGUAGE sql IMMUTABLE SET search_path = policy_jp, pg_temp AS $$
  SELECT p_code ~ '^[0-9]{6}$'
     AND (11 - ((substr(p_code, 1, 1)::INT * 6 + substr(p_code, 2, 1)::INT * 5 + substr(p_code, 3, 1)::INT * 4
                + substr(p_code, 4, 1)::INT * 3 + substr(p_code, 5, 1)::INT * 2) % 11)) % 10 = substr(p_code, 6, 1)::INT
$$;

-- 層級（正見 PLAN-task-activation 第 6 節的共用詞彙）：國政＝national、都道府県（知事・県議）＝regional、市区町村＝local
CREATE OR REPLACE FUNCTION policy_jp.election_level(p_election_type TEXT) RETURNS TEXT
LANGUAGE sql IMMUTABLE SET search_path = policy_jp, pg_temp AS $$
  SELECT CASE
           WHEN p_election_type IN ('national_lower', 'national_upper') THEN 'national'
           WHEN p_election_type IN ('governor', 'pref_assembly') THEN 'regional'
           WHEN p_election_type IN ('mayor', 'ward_mayor', 'town_mayor', 'muni_assembly') THEN 'local'
         END
$$;

GRANT EXECUTE ON FUNCTION policy_jp.lg_code_valid(TEXT), policy_jp.election_level(TEXT) TO anon, authenticated;

