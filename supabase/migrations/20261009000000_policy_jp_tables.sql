-- ------------------------------------------------------------
-- 12. 權限：每張表 RLS＋逐表 GRANT（公開資料只給讀）
-- ------------------------------------------------------------
DO $$
DECLARE t TEXT;
BEGIN
  -- 有 review_status 的表：公開讀只看得到 published
  FOREACH t IN ARRAY ARRAY['politicians', 'politician_careers', 'lineages', 'elections', 'politician_elections',
                           'candidacy_endorsements', 'politician_offices', 'policies', 'policy_elements', 'tracking_logs',
                           'lineage_participants', 'lineage_links', 'handovers'] LOOP
    EXECUTE format('ALTER TABLE policy_jp.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS "Public read published" ON policy_jp.%I', t);
    EXECUTE format('CREATE POLICY "Public read published" ON policy_jp.%I FOR SELECT TO anon, authenticated USING (review_status = ''published'')', t);
    EXECUTE format('GRANT SELECT ON policy_jp.%I TO anon, authenticated', t);
  END LOOP;
  -- 參照用的表與出處、查核紀錄：公開讀全部
  FOREACH t IN ARRAY ARRAY['sources', 'source_refs', 'local_governments', 'local_government_successions', 'parties',
