CREATE TABLE IF NOT EXISTS policy_jp.elections (
  id              TEXT PRIMARY KEY CHECK (id ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}_[a-z_]+_([0-9]{6}|national)$'),
  name            TEXT NOT NULL CHECK (btrim(name) <> ''),
  election_date   DATE NOT NULL,
  notice_date     DATE,
  election_type   TEXT NOT NULL CHECK (election_type IN ('governor', 'mayor', 'ward_mayor', 'town_mayor', 'national_lower',
                                                         'national_upper', 'pref_assembly', 'muni_assembly')),
  election_reason TEXT NOT NULL CHECK (election_reason IN ('regular', 'resignation', 'death', 'recall', 'dissolution',
                                                           'by_election', 'increase', 'rerun')),
  level           TEXT NOT NULL CHECK (level IN ('national', 'regional', 'local')),
  jurisdiction    TEXT NOT NULL DEFAULT 'jp' CHECK (jurisdiction = 'jp'),
  timezone        TEXT NOT NULL DEFAULT 'Asia/Tokyo' CHECK (timezone = 'Asia/Tokyo'),
  lg_code         TEXT REFERENCES policy_jp.local_governments(lg_code),
  seats           INTEGER CHECK (seats IS NULL OR seats > 0),
  turnout         NUMERIC(5, 2) CHECK (turnout IS NULL OR turnout BETWEEN 0 AND 100),
  lineage_id      TEXT REFERENCES policy_jp.lineages(id),
  note            TEXT,
  review_status   TEXT NOT NULL DEFAULT 'pending' CHECK (review_status IN ('pending', 'published', 'rejected', 'not_found')),
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT elections_level_matches_type CHECK (level = policy_jp.election_level(election_type)),
  CONSTRAINT elections_national_no_lg CHECK ((level = 'national') = (lg_code IS NULL)),
  CONSTRAINT elections_notice_before_polling CHECK (notice_date IS NULL OR notice_date <= election_date),
  -- 補欠・増員は議員選挙だけ
  CONSTRAINT elections_by_election_assembly CHECK (
    election_reason NOT IN ('by_election', 'increase')
    OR election_type IN ('pref_assembly', 'muni_assembly', 'national_lower', 'national_upper'))
);
CREATE INDEX IF NOT EXISTS elections_date_type_idx ON policy_jp.elections (election_date DESC, election_type);
CREATE INDEX IF NOT EXISTS elections_lg_date_idx ON policy_jp.elections (lg_code, election_date DESC);
COMMENT ON TABLE policy_jp.elections IS
  '選舉。id＝正見的 election_key：日期＋種類＋地區（2027-04-11_governor_130001；國政 2024-10-27_national_lower_national），'
  '同日同地區同種類只有一場，建立後不改（日期或種類填錯只改欄位）。scope_code（正見 PLAN 第 6 節）＝lg_code。'
  '候選人數不存，要時從 politician_elections 算。無投票当選記在 election_districts.is_uncontested';
COMMENT ON COLUMN policy_jp.elections.election_reason IS
  'regular 任期満了／resignation 辞職／death 死亡／recall 解職請求（リコール）成立後に行われる選挙——台灣的 recall 是罷免投票本身，日本這裡是解職後補選首長・議員的那場選舉／'
  'dissolution 不信任・出直し・解散／by_election 補欠選挙／increase 増員選挙／rerun 再選挙（當選無效、當選人不足等）';
COMMENT ON COLUMN policy_jp.elections.level IS '正見 PLAN 第 6 節：national 國政／regional 都道府県／local 市区町村，由 election_type 決定（CHECK）';
COMMENT ON COLUMN policy_jp.elections.turnout IS '投票率（%）。不是得票數也不是得票率；投票前為空';

CREATE TABLE IF NOT EXISTS policy_jp.election_districts (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  election_id       TEXT NOT NULL REFERENCES policy_jp.elections(id) ON DELETE CASCADE,
  district_kind     TEXT NOT NULL CHECK (district_kind IN ('district', 'proportional', 'at_large')),
  district_name     TEXT,
  district_lg_code  TEXT REFERENCES policy_jp.local_governments(lg_code),
  district_lg_codes TEXT[] NOT NULL DEFAULT '{}',
  seats             INTEGER CHECK (seats IS NULL OR seats > 0),
  seats_basis       TEXT CHECK (seats_basis IN ('law', 'notice')),
  is_uncontested    BOOLEAN,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT election_districts_unique UNIQUE NULLS NOT DISTINCT (election_id, district_kind, district_name),
  CONSTRAINT election_districts_name CHECK ((district_kind = 'at_large') = (district_name IS NULL)),
  CONSTRAINT election_districts_merged CHECK (cardinality(district_lg_codes) = 0 OR (district_lg_code IS NULL AND cardinality(district_lg_codes) >= 2)),
  CONSTRAINT election_districts_seats_basis CHECK ((seats IS NULL) = (seats_basis IS NULL))
);
COMMENT ON TABLE policy_jp.election_districts IS '選挙区と定数。各選挙区 seats 的合計不超過 elections.seats；有選挙区列的選舉，參選人的 district_kind＋district_name 要對得上其中一列';
