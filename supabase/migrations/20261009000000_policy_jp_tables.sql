  SELECT string_agg(c.table_name || '.' || c.column_name, ', ') INTO bad
    FROM information_schema.columns c
   WHERE c.table_schema = 'policy_jp' AND c.column_name ~* '(vote|votes|ballot_count|tokuhyo|得票)';
  IF bad IS NOT NULL THEN RAISE EXCEPTION 'policy_jp：日本站不存得票數、得票率：%', bad; END IF;
END
