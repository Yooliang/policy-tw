CREATE TABLE IF NOT EXISTS policy_jp.local_governments (
  lg_code              TEXT PRIMARY KEY CHECK (policy_jp.lg_code_valid(lg_code)),
  kind                 TEXT NOT NULL CHECK (kind IN ('prefecture', 'designated_city', 'core_city', 'city', 'special_ward',
                                                     'admin_ward', 'town', 'village')),
  pref_code            TEXT NOT NULL REFERENCES policy_jp.local_governments(lg_code),
  name                 TEXT NOT NULL CHECK (btrim(name) <> ''),
  kana                 TEXT NOT NULL CHECK (btrim(kana) <> ''),
  slug                 TEXT NOT NULL UNIQUE,
  assembly_seats       INTEGER CHECK (assembly_seats IS NULL OR assembly_seats > 0),
  assembly_seats_as_of DATE,
  valid_from           DATE,
  valid_to             DATE,
  created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT local_governments_pref_self CHECK ((kind = 'prefecture') = (pref_code = lg_code)),
  CONSTRAINT local_governments_seats_as_of CHECK ((assembly_seats IS NULL) = (assembly_seats_as_of IS NULL)),
  CONSTRAINT local_governments_admin_ward_no_assembly CHECK (kind <> 'admin_ward' OR assembly_seats IS NULL),
  CONSTRAINT local_governments_valid_period CHECK (valid_from IS NULL OR valid_to IS NULL OR valid_to >= valid_from)
);
CREATE INDEX IF NOT EXISTS local_governments_pref_idx ON policy_jp.local_governments (pref_code) WHERE valid_to IS NULL;
COMMENT ON TABLE policy_jp.local_governments IS
  '地方公共団体（主鍵＝總務省全国地方公共団体コード 6 碼含檢查碼）。admin_ward＝政令市的行政区（沒有選舉、沒有議會）。'
  '北方領土 6 村（016951〜017001）代碼表有但沒有議會，建議不收（docs/handoff 說明）';
COMMENT ON COLUMN policy_jp.local_governments.assembly_seats IS '議會的現行定數（#12 對帳的分母）；出處用 source_refs（target_table=local_governments）';

CREATE TABLE IF NOT EXISTS policy_jp.local_government_successions (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_lg_code TEXT NOT NULL REFERENCES policy_jp.local_governments(lg_code),
  to_lg_code   TEXT NOT NULL REFERENCES policy_jp.local_governments(lg_code),
  date         DATE NOT NULL,
  kind         TEXT NOT NULL CHECK (kind IN ('merge', 'absorb', 'split', 'rename')),
  note         TEXT,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT local_government_successions_distinct CHECK (from_lg_code <> to_lg_code OR kind = 'rename'),
  CONSTRAINT local_government_successions_unique UNIQUE (from_lg_code, to_lg_code, date)
);
COMMENT ON TABLE policy_jp.local_government_successions IS '合併・編入・分割・改名（總務省「改正一覧表」）。歷代首長與政策系譜跨合併接起來用';

