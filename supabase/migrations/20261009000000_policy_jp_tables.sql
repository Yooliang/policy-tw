-- ------------------------------------------------------------
-- 11. 健康檢查視圖（正常是空的）
-- ------------------------------------------------------------
-- 出處引用指到不存在的資料列（source_refs 是多型關聯，沒辦法用外鍵擋）
CREATE OR REPLACE VIEW policy_jp.source_refs_orphans WITH (security_invoker = true) AS
  SELECT r.* FROM policy_jp.source_refs r
   WHERE NOT CASE r.target_table
     WHEN 'elections'                    THEN EXISTS (SELECT 1 FROM policy_jp.elections x WHERE x.id = r.target_id)
     WHEN 'election_districts'           THEN EXISTS (SELECT 1 FROM policy_jp.election_districts x WHERE x.id::TEXT = r.target_id)
     WHEN 'politicians'                  THEN EXISTS (SELECT 1 FROM policy_jp.politicians x WHERE x.id = r.target_id)
     WHEN 'politician_careers'           THEN EXISTS (SELECT 1 FROM policy_jp.politician_careers x WHERE x.id::TEXT = r.target_id)
     WHEN 'politician_elections'         THEN EXISTS (SELECT 1 FROM policy_jp.politician_elections x WHERE x.id = r.target_id)
     WHEN 'politician_election_status'   THEN EXISTS (SELECT 1 FROM policy_jp.politician_elections x WHERE x.id = r.target_id)
     WHEN 'candidacy_endorsements'       THEN EXISTS (SELECT 1 FROM policy_jp.candidacy_endorsements x WHERE x.id = r.target_id)
     WHEN 'politician_offices'           THEN EXISTS (SELECT 1 FROM policy_jp.politician_offices x WHERE x.id = r.target_id)
     WHEN 'assembly_factions'            THEN EXISTS (SELECT 1 FROM policy_jp.assembly_factions x WHERE x.id = r.target_id)
     WHEN 'local_governments'            THEN EXISTS (SELECT 1 FROM policy_jp.local_governments x WHERE x.lg_code = r.target_id)
     WHEN 'local_government_successions' THEN EXISTS (SELECT 1 FROM policy_jp.local_government_successions x WHERE x.id::TEXT = r.target_id)
     WHEN 'parties'                      THEN EXISTS (SELECT 1 FROM policy_jp.parties x WHERE x.id = r.target_id)
     WHEN 'policies'                     THEN EXISTS (SELECT 1 FROM policy_jp.policies x WHERE x.id = r.target_id)
     WHEN 'policy_elements'              THEN EXISTS (SELECT 1 FROM policy_jp.policy_elements x WHERE x.id = r.target_id)
     WHEN 'tracking_logs'                THEN EXISTS (SELECT 1 FROM policy_jp.tracking_logs x WHERE x.id = r.target_id)
     WHEN 'lineages'                     THEN EXISTS (SELECT 1 FROM policy_jp.lineages x WHERE x.id = r.target_id)
     WHEN 'lineage_participants'         THEN EXISTS (SELECT 1 FROM policy_jp.lineage_participants x WHERE x.id = r.target_id)
     WHEN 'lineage_links'                THEN EXISTS (SELECT 1 FROM policy_jp.lineage_links x WHERE x.id = r.target_id)
     WHEN 'handovers'                    THEN EXISTS (SELECT 1 FROM policy_jp.handovers x WHERE x.id = r.target_id)
     WHEN 'reviews'                      THEN EXISTS (SELECT 1 FROM policy_jp.reviews x WHERE x.id::TEXT = r.target_id)
     ELSE false
   END;
COMMENT ON VIEW policy_jp.source_refs_orphans IS '指向不存在資料列的出處引用（正常是空的）。service_role 用，不開放 anon';

-- 公報・公告類還沒存檔的出處（archive_url 改成可空之後，靠這個視圖與之後的排程補上）
