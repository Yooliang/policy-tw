CREATE TABLE IF NOT EXISTS policy_jp.sources (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  url            TEXT NOT NULL UNIQUE,
  title          TEXT,
  publisher      TEXT,
  source_kind    TEXT NOT NULL DEFAULT 'other'
                 CHECK (source_kind IN ('official', 'self', 'assembly', 'statistics', 'media', 'other')),
  self_evidence  TEXT CHECK (self_evidence IN ('linked_by_official', 'mutual_link')),
  doc_kind       TEXT CHECK (doc_kind IN ('election_bulletin', 'election_notice')),
  published_date DATE,
  fetched_at     TIMESTAMPTZ,
  archive_url    TEXT,
  origin         TEXT NOT NULL CHECK (btrim(origin) <> ''),
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT sources_url_http CHECK (url ~* '^https?://'),
  CONSTRAINT sources_archive_url_http CHECK (archive_url IS NULL OR archive_url ~* '^https?://'),
  -- 本人來源一定要有認定根據；有根據就一定是本人來源（防冒名：沒有根據的本人帳號視為 media）
  CONSTRAINT sources_self_needs_evidence CHECK ((source_kind = 'self') = (self_evidence IS NOT NULL))
);
COMMENT ON TABLE policy_jp.sources IS '出處（一個網址一列），任何資料都用 source_refs 引用。正見 public.sources 的日本版（#39）';
COMMENT ON COLUMN policy_jp.sources.source_kind IS
  'official 自治体・選管公文、予算書、施政方針、選挙公報、告示、議会官網議員一覧／self 本人（需 self_evidence）／assembly 議会会議録／'
  'statistics 総務省・e-Stat・議長会調查（數字類）／media 新聞報導與沒有認定根據的社群／other 其他。'
  '正見只有四級：assembly 與 statistics 在正見都歸 official（兩站對照時這樣換算）';
COMMENT ON COLUMN policy_jp.sources.self_evidence IS
  '本人來源的認定根據：linked_by_official 被議會・選管・政黨官網連結／mutual_link 與本人官網互相連結。平台認證（platform_verified）不收：社群貼文不能標 self（同正見協議 1.62.0）';
COMMENT ON COLUMN policy_jp.sources.doc_kind IS 'election_bulletin 選挙公報／election_notice 選管的告示・結果；這兩類要存檔（archive_url），見視圖 source_archive_missing';
COMMENT ON COLUMN policy_jp.sources.fetched_at IS '擷取時間；不知道就留空，不編造（同正見）';
COMMENT ON COLUMN policy_jp.sources.archive_url IS
  '存檔網址。公報・公告類必須有，但改成「可空＋健康檢查」：交件當下先登記，由排程補存檔（SCHEMA v0.7 寫必填，見待定事項 2）。'
  '總務省 robots.txt 擋 Internet Archive，總務省頁面要用國立國會圖書館 WARP 或其他方式';
COMMENT ON COLUMN policy_jp.sources.origin IS '這列最早從哪裡來（contribution＝任務回報落庫、manual＝維護者手動 等）';

CREATE TABLE IF NOT EXISTS policy_jp.source_refs (
  source_id    BIGINT NOT NULL REFERENCES policy_jp.sources(id) ON DELETE CASCADE,
  target_table TEXT NOT NULL CHECK (target_table IN (
                 'elections', 'election_districts', 'politicians', 'politician_careers', 'politician_elections',
                 'politician_election_status', 'candidacy_endorsements', 'politician_offices', 'assembly_factions',
                 'local_governments', 'local_government_successions', 'parties', 'policies', 'policy_elements',
                 'tracking_logs', 'lineages', 'lineage_participants', 'lineage_links', 'handovers', 'reviews')),
  target_id    TEXT NOT NULL,
  role         TEXT NOT NULL DEFAULT 'primary' CHECK (role IN ('primary', 'supporting')),
  origin       TEXT NOT NULL CHECK (btrim(origin) <> ''),
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (target_table, target_id, source_id)
);
CREATE INDEX IF NOT EXISTS source_refs_source_idx ON policy_jp.source_refs (source_id);
COMMENT ON TABLE policy_jp.source_refs IS
  '哪一筆資料引用了哪個出處（同正見 public.source_refs）。role：primary＝主要出處／supporting＝一併附上的其他來源。'
  'target_table＝politician_election_status：參選「目前狀態」的出處（SCHEMA 的 status_source_ids；沒有就不顯示那筆參選）；'
  'target_table＝reviews：查核紀錄依據的出處（SCHEMA 的 evidence_source_ids）。指向不存在的資料列看視圖 source_refs_orphans';

